# 创建股本信息表（如果不存在）并添加注释
def create_stock_shares_table(conn):
    """
    创建股本信息表（如果不存在）并添加注释
    """
    table_name = 'ok_finance_stock_shares'
    try:
        if not table_exists(conn, table_name):
            cur = conn.cursor()
            # 修改字段类型为 VARCHAR(64)
            cur.execute(sql.SQL("""
                CREATE TABLE {} (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                    stock_code VARCHAR(64) NOT NULL,
                    total_shares NUMERIC(20, 0),
                    limit_shares NUMERIC(20, 0),
                    list_a_shares NUMERIC(20, 0),
                    change_reason VARCHAR(64),
                    change_date VARCHAR(64) NOT NULL,  -- 修改为 VARCHAR
                    UNIQUE(stock_code, change_date)
                );
            """).format(sql.Identifier(table_name)))
            
            # 更新字段注释
            cur.execute(sql.SQL("COMMENT ON COLUMN {}.stock_code IS '股票代码（最大长度64字符）';").format(sql.Identifier(table_name)))
            cur.execute(sql.SQL("COMMENT ON COLUMN {}.change_reason IS '变更原因（最大长度64字符）';").format(sql.Identifier(table_name)))
            cur.execute(sql.SQL("COMMENT ON COLUMN {}.change_date IS '变更日期（YYYY-MM-DD格式字符串）';").format(sql.Identifier(table_name)))

            # 索引保持不变
            cur.execute(sql.SQL("CREATE INDEX idx_stock_shares_stock_code ON {} (stock_code);").format(sql.Identifier(table_name)))
            cur.execute(sql.SQL("CREATE INDEX idx_stock_shares_change_date ON {} (change_date);").format(sql.Identifier(table_name)))
            
            conn.commit()
            print(f"Table {table_name} 创建成功（使用VARCHAR类型）")
        else:
            print(f"Table {table_name} 已存在")
    except Exception as e:
        print(f"创建表失败: {e}")

def insert_or_update_stock_shares(conn, stock_code, shares_data):
    """
    插入或更新股本信息（适配VARCHAR类型）
    """
    try:
        # 转换日期格式为字符串
        if 'change_date' in shares_data.columns:
            shares_data['change_date'] = shares_data['change_date'].astype(str)
            
        # 处理数值字段空值
        numeric_cols = ['total_shares', 'limit_shares', 'list_a_shares']
        for col in numeric_cols:
            shares_data[col] = shares_data[col].apply(lambda x: x if pd.notnull(x) else None)

        # 批量插入
        extras.execute_values(
            conn.cursor(),
            """
            INSERT INTO ok_finance_stock_shares (
                stock_code, total_shares, limit_shares, list_a_shares, 
                change_reason, change_date
            )
            VALUES %s
            ON CONFLICT (stock_code, change_date) DO UPDATE
            SET
                total_shares = EXCLUDED.total_shares,
                limit_shares = EXCLUDED.limit_shares,
                list_a_shares = EXCLUDED.list_a_shares,
                change_reason = EXCLUDED.change_reason
            """,
            [
                (
                    stock_code,
                    row['total_shares'],
                    row['limit_shares'],
                    row['list_a_shares'],
                    str(row['change_reason'])[:64],  # 确保不超过64字符
                    str(row['change_date'])[:10]     # 截取前10位 YYYY-MM-DD
                )
                for _, row in shares_data.iterrows()
            ],
            page_size=500
        )
        conn.commit()
        print(f"成功更新 {len(shares_data)} 条股本数据（股票代码：{stock_code}）")
    except Exception as e:
        print(f"数据更新失败: {e}")
        conn.rollback()

# 获取股本信息
def fetch_stock_shares(stock_code, is_history=True):
    try:
        df = adata.stock.info.get_stock_shares(stock_code=stock_code, is_history=is_history)
        print(f"Fetched stock shares data for stock {stock_code} successfully!")
        return df
    except Exception as e:
        print(f"Error fetching stock shares data for stock {stock_code}: {e}")
        return None

