def fetch_and_store_finance_core_index(conn, clear_data):
    try:
        create_finance_core_index_table(conn)

        if clear_data:
            cur = conn.cursor()
            cur.execute("DELETE FROM ok_finance_stock_core_index;")
            conn.commit()
            print("Cleared all finance core index data.")

        all_stocks_df = adata.stock.info.all_code()
        stock_codes = all_stocks_df['stock_code'].tolist()

        for stock_code in stock_codes:
            if not clear_data and finance_core_index_exists(conn, stock_code):
                print(f"Finance core index for {stock_code} already exists, skipping.")
                continue
            
            print(f"Fetching finance core index for stock code: {stock_code}")
            try:
                core_index_data = adata.stock.finance.get_core_index(stock_code=stock_code)

                if core_index_data.empty:
                    print(f"No finance core index information found for stock code: {stock_code}")
                    continue

                insert_finance_core_index(conn, core_index_data)

            except Exception as e:
                print(f"Error fetching finance core index for {stock_code}: {e}")

    except Exception as e:
        print(f"Error fetching or storing finance core index information: {e}")

def main(clear_data=True):
    conn = connect_to_db()
    if conn is None:
        return

    try:
        fetch_and_store_finance_core_index(conn, clear_data)

    finally:
        conn.close()

