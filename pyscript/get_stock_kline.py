            daily_data = fetch_kline_data(stock_code, k_type=2, start_date=start_date)
            if daily_data is not None:
                insert_kline_data(conn, weekly_table, stock_code, daily_data)

            # 获取当前股票的最新交易日
            latest_date = get_latest_trade_date(conn, monthly_table, stock_code)
            
            # 如果存在最新交易日，则从该日期开始更新；否则从 2020 年开始插入
